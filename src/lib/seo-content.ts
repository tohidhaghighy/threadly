export function getCategorySeoCopy(title: string, apiDescription?: string | null): CategorySeoCopy {
  const known = CATEGORY_SEO[title];
  if (known) {
    return {
      short: apiDescription?.trim() || known.short,
      long: apiDescription?.trim() ? `${apiDescription.trim()} ${known.long}` : known.long,
    };
  }
  const fallback = apiDescription?.trim() ?? "";
  return {
    short: fallback || title,
    long: fallback || `گفتگوها و سوالات مرتبط با ${title} در انجمن فاطر.`,
  };
}
